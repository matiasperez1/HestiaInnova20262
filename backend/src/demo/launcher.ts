import { spawn, spawnSync } from "node:child_process";
import {
  mkdirSync,
  existsSync,
  readFileSync,
  openSync,
  closeSync,
} from "node:fs";
import { resolve, dirname, normalize } from "node:path";
import pg from "pg";
import { DemoStore, personas } from "./store.js";
import { backendRoot, demoConfig } from "./config.js";
const cfg = demoConfig();
mkdirSync(cfg.dataDir, { recursive: true });
const executable = (name: string) => {
  const found = spawnSync(
    process.platform === "win32" ? "where.exe" : "which",
    [name],
    { encoding: "utf8", windowsHide: true },
  );
  if (found.status !== 0)
    throw new Error(
      "PostgreSQL is required for this demo; use the existing PostgreSQL installation and add its bin directory to this terminal PATH. No software is installed automatically.",
    );
  return found.stdout.trim().split(/\r?\n/)[0]!;
};
const bin = dirname(executable("pg_ctl"));
const tool = (name: string) =>
  resolve(bin, name + (process.platform === "win32" ? ".exe" : ""));
const data = resolve(cfg.dataDir, "postgres");
function run(name: string, args: string[], allowFailure = false) {
  const log = openSync(resolve(cfg.dataDir, "postgres-setup.log"), "a");
  let r;
  try {
    r = spawnSync(tool(name), args, {
      windowsHide: true,
      stdio: ["ignore", log, log],
    });
  } finally {
    closeSync(log);
  }
  if (r.status !== 0 && !allowFailure)
    throw new Error(
      "LOCAL_DEMO PostgreSQL setup failed; inspect the local setup log. No remote database is used.",
    );
  return r.status;
}
if (!existsSync(resolve(data, "PG_VERSION")))
  run("initdb", [
    "-D",
    data,
    "-U",
    "postgres",
    "--auth=trust",
    "--encoding=UTF8",
    "--locale=C",
  ]);
const alreadyRunning = run("pg_ctl", ["-D", data, "status"], true) === 0;
if (!alreadyRunning)
  run("pg_ctl", [
    "-D",
    data,
    "-l",
    resolve(cfg.dataDir, "postgres.log"),
    "-o",
    `-h 127.0.0.1 -p ${cfg.databasePort}`,
    "-w",
    "start",
  ]);
const admin = new pg.Pool({
  connectionString: `postgresql://postgres@127.0.0.1:${cfg.databasePort}/postgres`,
  connectionTimeoutMillis: 3000,
});
const location = (await admin.query("SHOW data_directory")).rows[0]
  .data_directory;
if (normalize(location).toLowerCase() !== normalize(data).toLowerCase())
  throw new Error(
    "Refusing to touch an unrelated PostgreSQL cluster on the configured port",
  );
if (
  !(await admin.query("SELECT 1 FROM pg_database WHERE datname='hestia_demo'"))
    .rowCount
)
  await admin.query("CREATE DATABASE hestia_demo");
await admin.end();
const pool = new pg.Pool({ connectionString: cfg.connectionString });
if (
  !(await pool.query("SELECT to_regclass('demo.identity') present")).rows[0]
    .present
) {
  const bootstrap = readFileSync(
    resolve(backendRoot, "demo/bootstrap.sql"),
    "utf8",
  ).replace(/^\uFEFF/, "");
  const migration = readFileSync(
    resolve(
      backendRoot,
      "../supabase/migrations/202611160001_gmail_automatic.sql",
    ),
    "utf8",
  )
    .replace(/^BEGIN;$/m, "")
    .replace(/^COMMIT;$/m, "");
  const schema = readFileSync(
    resolve(backendRoot, "demo/schema.sql"),
    "utf8",
  ).replace(/^\uFEFF/, "");
  await pool.query("BEGIN;" + bootstrap + migration + schema + "COMMIT;");
}
// The demo notification stream needs a commit-ordered cursor, including on existing local clusters.
await pool.query(`ALTER TABLE demo.notification ADD COLUMN IF NOT EXISTS delivery_seq bigint GENERATED BY DEFAULT AS IDENTITY`);
await pool.query(`CREATE UNIQUE INDEX IF NOT EXISTS demo_notification_delivery_seq ON demo.notification(delivery_seq)`);
const store = new DemoStore(pool);
for (const user of Object.values(personas)) await store.activate(user);
await pool.end();
console.log(
  "LOCAL_DEMO ready: isolated PostgreSQL, no external service credentials",
);
if (process.argv.includes("--prepare-only")) process.exit(0);
const children = ["api-main.js", "worker-main.js"].map((file) =>
  spawn(process.execPath, [resolve(backendRoot, "dist/src/demo", file)], {
    stdio: "inherit",
    windowsHide: true,
    env: { ...process.env, LOCAL_DEMO: "true" },
  }),
);
let stopped = false;
function stop() {
  if (stopped) return;
  stopped = true;
  for (const child of children) child.kill();
  if (!alreadyRunning)
    run("pg_ctl", ["-D", data, "-m", "fast", "-w", "stop"], true);
}
for (const signal of ["SIGINT", "SIGTERM"] as const)
  process.on(signal, () => {
    stop();
  });
for (const child of children)
  child.on("exit", (code) => {
    if (!stopped && code !== 0) process.exitCode = 1;
    stop();
  });
